"""Generate the Luau design modules from docs/design (the source of truth).

    python tools/gen_design.py

writes
    crates/app/ui/theme/tokens.luau  every token of docs/design/tokens.json, dark and light
    crates/app/ui/lib/icons.luau     the Icons board of docs/design/screens.html, as SVG

Run it again after the design files change; `cargo test -p recap` fails while
the generated files are stale (tests/design_sync.rs).
"""

import html.parser
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DESIGN = ROOT / "docs" / "design"
UI = ROOT / "crates" / "app" / "ui"


def token_name(name: str) -> str:
    # tokens.json uses hyphens (`text-primary`); zgx tokens are dotted, under
    # the app's own namespace: `$rc.text.primary`.
    return "rc." + name.replace("-", ".")


def gen_tokens() -> str:
    data = json.loads((DESIGN / "tokens.json").read_text(encoding="utf-8"))["tokens"]
    dark, light = {}, {}
    for name in sorted(data):
        value = data[name]["value"]
        if isinstance(value, list):
            for v in value:
                (dark if v["theme"]["mode"] == "dark" else light)[name] = v["value"]
        else:
            dark[name] = light[name] = value

    def table(values: dict) -> str:
        return "\n".join(f'\t\t["{token_name(n)}"] = "{v}",' for n, v in sorted(values.items()))

    return f"""--!strict
-- GENERATED by tools/gen_design.py from docs/design/tokens.json. Don't edit:
-- change the JSON and run `python tools/gen_design.py`.
--
-- Every design token as `$rc.<name>` (hyphens become dots: `text-primary` is
-- `$rc.text.primary`), in two themes: recap-dark (the default) and
-- recap-light. zgx's standard tokens (text, background, accent, fonts) follow
-- ours, so zgx's own widgets match.

local M = {{}}

M.dark = {{
{table(dark)}
}}

M.light = {{
{table(light)}
}}

return M
"""


class IconBoard(html.parser.HTMLParser):
    """Reads the `Icons` section: each icon is a div of <svg>s and a <p> name."""

    def __init__(self):
        super().__init__()
        self.inside = False
        self.depth = 0
        self.paths = []
        self.icons = []
        self.name_next = False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "section":
            self.inside = a.get("aria-label") == "Icons"
            return
        if not self.inside:
            return
        if tag == "path":
            filled = a.get("fill", "none") != "none"
            stroked = "stroke" in a
            self.paths.append((a["d"], filled, stroked, a.get("stroke-width", "1.5")))
        elif tag == "p" and self.paths:
            self.name_next = True

    def handle_endtag(self, tag):
        if tag == "section":
            self.inside = False

    def handle_data(self, data):
        if self.name_next and data.strip():
            self.icons.append((data.strip(), self.paths))
            self.paths = []
            self.name_next = False


def gen_icons() -> str:
    board = IconBoard()
    board.feed((DESIGN / "screens.html").read_text(encoding="utf-8"))
    lines = []
    for name, paths in board.icons:
        parts = []
        for d, filled, stroked, width in paths:
            fill = "#fff" if filled else "none"
            stroke = f' stroke="#fff" stroke-width="{width}"' if stroked else ""
            parts.append(f'<path d="{d}" fill="{fill}"{stroke}/>')
        svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">' + "".join(parts) + "</svg>"
        lines.append(f'\t["{name}"] = [[{svg}]],')
    body = "\n".join(lines)
    return f"""--!strict
-- GENERATED by tools/gen_design.py from the Icons board of
-- docs/design/screens.html. Don't edit or redraw: change the board and run
-- `python tools/gen_design.py`.
--
-- 16-unit SVG, drawn white: tint it (`ui.svg {{ code = icons.svg.pause, tint = "$rc.text.secondary" }}`),
-- or use components/icon.luau.

local M = {{}}

M.svg = {{
{body}
}}

return M
"""


def main():
    (UI / "theme").mkdir(parents=True, exist_ok=True)
    (UI / "lib").mkdir(parents=True, exist_ok=True)
    (UI / "theme" / "tokens.luau").write_text(gen_tokens(), encoding="utf-8", newline="\n")
    (UI / "lib" / "icons.luau").write_text(gen_icons(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
