"""Generate the Luau design modules from docs/design (the source of truth).

    python tools/gen_design.py

writes
    crates/app/ui/theme/tokens.luau  every token of docs/design/tokens.json, dark and light
    crates/app/ui/lib/icons.luau     the Icons board of docs/design/screens.html, as SVG
    crates/app/ui/lib/logos.luau     the Provider logos board, as SVG in brand colours

Run it again after the design files change; `cargo test -p recap` fails while
the generated files are stale (tests/design_sync.rs).
"""

import html.parser
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DESIGN = ROOT / "docs" / "design"
UI = ROOT / "crates" / "app" / "ui"


def token_name(name: str) -> str:
    # tokens.json uses hyphens (`text-primary`); zgx tokens are dotted, under
    # the app's own namespace: `$rc.text.primary`.
    return "rc." + name.replace("-", ".")


def gen_tokens() -> str:
    data = json.loads((DESIGN / "tokens.json").read_text(encoding="utf-8"))["tokens"]
    dark, light = {}, {}
    for name in sorted(data):
        value = data[name]["value"]
        if isinstance(value, list):
            for v in value:
                (dark if v["theme"]["mode"] == "dark" else light)[name] = v["value"]
        else:
            dark[name] = light[name] = value

    def table(values: dict) -> str:
        return "\n".join(f'\t\t["{token_name(n)}"] = "{v}",' for n, v in sorted(values.items()))

    return f"""--!strict
-- GENERATED by tools/gen_design.py from docs/design/tokens.json. Don't edit:
-- change the JSON and run `python tools/gen_design.py`.
--
-- Every design token as `$rc.<name>` (hyphens become dots: `text-primary` is
-- `$rc.text.primary`), in two themes: recap-dark (the default) and
-- recap-light. zgx's standard tokens (text, background, accent, fonts) follow
-- ours, so zgx's own widgets match.

local M = {{}}

M.dark = {{
{table(dark)}
}}

M.light = {{
{table(light)}
}}

return M
"""


class IconBoard(html.parser.HTMLParser):
    """Reads the `Icons` section: each icon is a div of <svg>s and a <p> name."""

    def __init__(self):
        super().__init__()
        self.inside = False
        self.depth = 0
        self.paths = []
        self.icons = []
        self.name_next = False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "section":
            self.inside = a.get("aria-label") == "Icons"
            return
        if not self.inside:
            return
        if tag == "path":
            filled = a.get("fill", "none") != "none"
            stroked = "stroke" in a
            self.paths.append((a["d"], filled, stroked, a.get("stroke-width", "1.5")))
        elif tag == "p" and self.paths:
            self.name_next = True

    def handle_endtag(self, tag):
        if tag == "section":
            self.inside = False

    def handle_data(self, data):
        if self.name_next and data.strip():
            self.icons.append((data.strip(), self.paths))
            self.paths = []
            self.name_next = False


def gen_icons() -> str:
    board = IconBoard()
    board.feed((DESIGN / "screens.html").read_text(encoding="utf-8"))
    lines = []
    for name, paths in board.icons:
        parts = []
        for d, filled, stroked, width in paths:
            fill = "#fff" if filled else "none"
            stroke = f' stroke="#fff" stroke-width="{width}"' if stroked else ""
            parts.append(f'<path d="{d}" fill="{fill}"{stroke}/>')
        svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">' + "".join(parts) + "</svg>"
        lines.append(f'\t["{name}"] = [[{svg}]],')
    body = "\n".join(lines)
    return f"""--!strict
-- GENERATED by tools/gen_design.py from the Icons board of
-- docs/design/screens.html. Don't edit or redraw: change the board and run
-- `python tools/gen_design.py`.
--
-- 16-unit SVG, drawn white: tint it (`ui.svg {{ code = icons.svg.pause, tint = "$rc.text.secondary" }}`),
-- or use components/icon.luau.

local M = {{}}

M.svg = {{
{body}
}}

return M
"""


class LogoBoard(html.parser.HTMLParser):
    """Reads the `Provider logos` section: each logo is an <svg> (placed in
    its 16-point box by its CSS class) and a <p> name."""

    def __init__(self):
        super().__init__()
        self.inside = False
        self.svg = None
        self.logos = []
        self.name_next = False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "section":
            self.inside = a.get("aria-label") == "Provider logos"
            return
        if not self.inside:
            return
        if tag == "svg":
            self.svg = {"class": a.get("class", ""), "viewBox": a["viewbox"], "paths": []}
        elif tag == "path" and self.svg is not None:
            self.svg["paths"].append(a)
        elif tag == "p" and self.svg is not None:
            self.name_next = True

    def handle_endtag(self, tag):
        if tag == "section":
            self.inside = False

    def handle_data(self, data):
        if self.name_next and data.strip():
            self.logos.append((data.strip(), self.svg))
            self.svg = None
            self.name_next = False


def brand(name: str) -> str:
    return json.loads((DESIGN / "tokens.json").read_text(encoding="utf-8"))["tokens"][name]["value"]


def gradients() -> dict:
    """The board's export lost the Gemini and Mistral gradient fills (their
    paths say fill="none"); their colours are tokens (`brand-gemini-a..c`,
    `brand-mistral-1..5`). Gemini runs diagonally; Mistral is five bands,
    one per row of its mark."""
    gemini = [(o, brand(f"brand-gemini-{k}")) for o, k in (("0", "a"), ("0.5", "b"), ("1", "c"))]
    mistral = []
    for i in range(5):
        colour = brand(f"brand-mistral-{i + 1}")
        mistral += [(num(i / 5), colour), (num((i + 1) / 5), colour)]
    return {
        "gemini": ('x1="0" y1="0" x2="1" y2="1"', gemini),
        "mistral": ('x1="0" y1="0" x2="0" y2="1"', mistral),
    }


def css_box(css: str, cls: str):
    m = re.search(r"\." + re.escape(cls) + r"\s*\{([^}]*)\}", css)
    assert m, f"no CSS for .{cls}"
    props = dict(re.findall(r"([a-z-]+):\s*([-\d.]+)px", m.group(1)))
    return tuple(float(props[k]) for k in ("left", "top", "width", "height"))


def num(x: float) -> str:
    return f"{x:.4f}".rstrip("0").rstrip(".")


def gen_logos() -> str:
    page = (DESIGN / "screens.html").read_text(encoding="utf-8")
    board = LogoBoard()
    board.feed(page)
    GRADIENTS = gradients()
    lines = []
    for name, svg in board.logos:
        key = "compatible" if name == "Compatible API" else name.lower().replace(" ", "_")
        left, top, width, height = css_box(page, svg["class"])
        _, _, vw, vh = (float(v) for v in svg["viewBox"].split())
        tinted = True
        defs = ""
        parts = []
        for p in svg["paths"]:
            style = p.get("style", "")
            fill, stroke = p.get("fill", "#000"), p.get("stroke")
            attrs = ""
            if "fill-rule" in p:
                attrs += f' fill-rule="{p["fill-rule"]}"'
            if stroke:
                attrs += f' fill="none" stroke="#fff" stroke-width="{p.get("stroke-width", "1.5")}"'
            elif fill == "none" and key in GRADIENTS:
                direction, stops = GRADIENTS[key]
                stop_tags = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in stops)
                defs = f'<defs><linearGradient id="g" {direction}>{stop_tags}</linearGradient></defs>'
                attrs += ' fill="url(#g)"'
                tinted = False
            elif "--text-primary" in style or fill.upper() == "#FFFFFF":
                attrs += ' fill="#fff"'
            else:
                attrs += f' fill="{fill}"'
                tinted = False
            parts.append(f'<path d="{p["d"]}"{attrs}/>')
        transform = f"translate({num(left)} {num(top)}) scale({num(width / vw)} {num(height / vh)})"
        body = (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">{defs}'
            f'<g transform="{transform}">{"".join(parts)}</g></svg>'
        )
        lines.append(f'\t["{key}"] = {{ tint = {str(tinted).lower()}, svg = [[{body}]] }},')
    body = "\n".join(lines)
    return f"""--!strict
-- GENERATED by tools/gen_design.py from the Provider logos board of
-- docs/design/screens.html, each placed in its 16-point box with the board's
-- optical offset. Don't edit or redraw: change the board and run
-- `python tools/gen_design.py`.
--
-- `tint = true`: a black brand mark drawn white, to tint `$rc.text.primary`
-- (it flips with the theme). Otherwise its brand colours. Use
-- components/logo.luau.

export type Logo = {{ tint: boolean, svg: string }}

local M = {{}}

M.logos = {{
{body}
}} :: {{ [string]: Logo }}

return M
"""


def main():
    (UI / "theme").mkdir(parents=True, exist_ok=True)
    (UI / "lib").mkdir(parents=True, exist_ok=True)
    (UI / "theme" / "tokens.luau").write_text(gen_tokens(), encoding="utf-8", newline="\n")
    (UI / "lib" / "icons.luau").write_text(gen_icons(), encoding="utf-8", newline="\n")
    (UI / "lib" / "logos.luau").write_text(gen_logos(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
