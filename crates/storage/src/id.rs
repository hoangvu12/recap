//! Meeting ids: when the meeting started, UTC, as `YYYYMMDD-HHMMSS`, so
//! folders sort by time and say when they are from.

/// The id's base for `epoch_ms`.
pub(crate) fn base(epoch_ms: u64) -> String {
    let secs = epoch_ms / 1000;
    let (days, rest) = (secs / 86_400, secs % 86_400);
    let (y, m, d) = civil_from_days(days as i64);
    format!("{y:04}{m:02}{d:02}-{:02}{:02}{:02}", rest / 3600, rest % 3600 / 60, rest % 60)
}

/// Howard Hinnant's `civil_from_days`: days since 1970-01-01 to (y, m, d).
fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (if m <= 2 { y + 1 } else { y }, m, d)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ids_read_as_utc_dates() {
        assert_eq!(base(0), "19700101-000000");
        assert_eq!(base(1_794_823_200_000), "20261116-100000");
        assert_eq!(base(951_782_400_000 + 59_000), "20000229-000059");
    }
}
